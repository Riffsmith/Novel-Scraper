// ─────────────────────────────────────────────────────────────────────────────
//  scripts/benchmark.ts
//
//  Phase 6 §1.7 / §2.3: drop-in benchmark harness. Measures chapters/minute and
//  peak RSS at concurrency 1 / 2 / 4 against a 200-chapter fixture served by a
//  local HTTP server (no network). Prints a markdown table; with `--write` it
//  also writes `docs/benchmarks/v2.0.0.md`.
//
//  v2.0.0 ships ADR-P6-A in `docs/phase-6/adr.md` INSTEAD of the numbers file -
//  the user elected the ADR-skip path (v2 ports v1's queue math verbatim, so
//  by construction chapters/minute at a given concurrency is unchanged). This
//  script is ready for any future contributor who elects a real run.
//
//  Run: `pnpm tsx scripts/benchmark.ts [--write]`
//  Requires `CLOAKBROWSER_BINARY_AVAILABLE=1` so a real browser is launched.
// ─────────────────────────────────────────────────────────────────────────────

import http from "http";
import fs from "fs";
import path from "path";
import os from "os";
import { fileURLToPath } from "url";

import { runJob } from "../src/app/runJob.js";
import { createDefaultWinstonLogger } from "../src/adapters/logger-winston/WinstonLogger.js";
import { NoopUIAdapter } from "../src/adapters/ui-noop/NoopUIAdapter.js";
import type { JobConfig } from "../src/core/domain/JobConfig.js";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const SHOULD_RUN = process.env.CLOAKBROWSER_BINARY_AVAILABLE === "1";
const WRITE = process.argv.includes("--write");

interface BenchRow {
  concurrency: number;
  chapters: number;
  scrapeMs: number;
  chaptersPerMin: number;
  peakRssMb: number;
}

function mkFixtureServer(root: string): Promise<{ server: http.Server; port: number }> {
  return new Promise((resolve) => {
    const server = http.createServer((req, res) => {
      const url = req.url ?? "/";
      if (url === "/") {
        res.writeHead(200, { "Content-Type": "text/html" });
        res.end("<html><body><a href='/toc.html'>toc</a></body></html>");
        return;
      }
      const file = path.join(root, url);
      if (fs.existsSync(file)) {
        res.writeHead(200, { "Content-Type": "text/html" });
        res.end(fs.readFileSync(file, "utf8"));
      } else {
        res.writeHead(404);
        res.end("not found");
      }
    });
    server.listen(0, "127.0.0.1", () => {
      const addr = server.address() as { port: number };
      resolve({ server, port: addr.port });
    });
  });
}

function buildFixture(workDir: string, n: number): void {
  const toc: string[] = [];
  for (let i = 1; i <= n; i++) {
    const html = `<!DOCTYPE html><html><head><title>Chapter ${i}</title></head>
<body><h1 class="t">Chapter ${i}</h1><div class="c"><p>Content ${i} word word word.</p></div></body></html>`;
    fs.writeFileSync(path.join(workDir, `c${i}.html`), html);
    toc.push(`<a href="/c${i}.html">Chapter ${i}</a>`);
  }
  const tocHtml = `<!DOCTYPE html><html><head><title>TOC</title></head>
<body>${toc.join("<br/>")}</body></html>`;
  fs.writeFileSync(path.join(workDir, "toc.html"), tocHtml);
}

async function runOnce(
  port: number,
  workDir: string,
  concurrency: number,
  n: number,
): Promise<BenchRow> {
  const outDir = path.join(workDir, `out-c${concurrency}`);
  const job: JobConfig = {
    method: "toc",
    tocUrl: `http://127.0.0.1:${port}/toc.html`,
    contentSelector: ".c",
    separateTitle: true,
    titleSelector: ".t",
    excludeSelectors: [],
    metadata: { title: "Bench", author: "Test", language: "en", coverSource: "none" },
    outputDir: outDir,
    outputFilename: `bench-c${concurrency}`,
    concurrency,
    delayMin: 0,
    delayMax: 0,
    headless: true,
    output: { epub: true },
  };

  const log = createDefaultWinstonLogger();
  const ui = new NoopUIAdapter();
  const before = process.memoryUsage().rss;
  const t0 = Date.now();
  const result = await runJob(job, { log, ui });
  const elapsedMs = Date.now() - t0;
  const peakRss = process.memoryUsage().rss;

  const chapters = result.chapters.length;
  if (chapters !== n) {
    throw new Error(
      `benchmark: expected ${n} chapters at concurrency=${concurrency}, got ${chapters}`,
    );
  }
  const chaptersPerMin = chapters > 0 ? (chapters / elapsedMs) * 60_000 : 0;
  return {
    concurrency,
    chapters,
    scrapeMs: elapsedMs,
    chaptersPerMin,
    peakRssMb: Math.max(peakRss, before) / (1024 * 1024),
  };
}

function renderMarkdown(rows: BenchRow[]): string {
  const header =
    "# v2.0.0 Benchmark\n\n" +
    "Generated by `pnpm tsx scripts/benchmark.ts --write`. Measures chapters/minute and peak RSS " +
    "across concurrency 1, 2, 4 against a 200-chapter local HTTP fixture (no network). The " +
    "fixture mirrors `tests/acceptance.test.ts` - a TOC page plus N chapter pages whose body is a " +
    "single short paragraph; the scrape is dominated by the queue, not by content length.\n\n" +
    "Per ADR-P6-A in `docs/phase-6/adr.md`, v2 ports v1's queue math verbatim, so the absolute " +
    "chapters/minute at a given concurrency is expected to be unchanged vs. v1. Peak RSS may differ " +
    "slightly from v1 (v2 adds the event-bus + UIAdapter indirection per chapter, negligible).\n\n";
  const table =
    "| Concurrency | Chapters | Elapsed (s) | Chapters/min | Peak RSS (MB) |\n" +
    "|-------------|----------|-------------|--------------|---------------|\n" +
    rows
      .map(
        (r) =>
          `| ${r.concurrency} | ${r.chapters} | ${(r.scrapeMs / 1000).toFixed(1)} | ${r.chaptersPerMin.toFixed(1)} | ${r.peakRssMb.toFixed(1)} |`,
      )
      .join("\n");
  const footer =
    "\n\nRun with `CLOAKBROWSER_BINARY_AVAILABLE=1 pnpm tsx scripts/benchmark.ts --write` to " +
    "regenerate this file. The fixture directory is created fresh per run under the OS tmpdir.\n";
  return header + table + footer;
}

async function main(): Promise<void> {
  if (!SHOULD_RUN) {
    console.error(
      "benchmark.ts requires CLOAKBROWSER_BINARY_AVAILABLE=1 (real CloakBrowser binary). Run:",
      "CLOAKBROWSER_BINARY_AVAILABLE=1 pnpm tsx scripts/benchmark.ts [--write]",
    );
    process.exit(2);
  }

  const N = 200;
  const workDir = fs.mkdtempSync(path.join(os.tmpdir(), "wns-bench-"));
  buildFixture(workDir, N);

  const { server, port } = await mkFixtureServer(workDir);
  const rows: BenchRow[] = [];
  try {
    for (const c of [1, 2, 4]) {
      process.stdout.write(`Running concurrency=${c} ... `);
      const row = await runOnce(port, workDir, c, N);
      console.log(`${row.chapters} chapters in ${(row.scrapeMs / 1000).toFixed(1)}s = ${row.chaptersPerMin.toFixed(1)} chapters/min`);
      rows.push(row);
    }
  } finally {
    await new Promise<void>((r) => server.close(() => r()));
    fs.rmSync(workDir, { recursive: true, force: true });
  }

  const markdown = renderMarkdown(rows);
  console.log("\n" + markdown);

  if (WRITE) {
    const outPath = path.resolve(__dirname, "..", "docs", "benchmarks", "v2.0.0.md");
    fs.mkdirSync(path.dirname(outPath), { recursive: true });
    fs.writeFileSync(outPath, markdown, "utf8");
    console.log(`\nWrote ${path.relative(process.cwd(), outPath)}`);
  } else {
    console.log("\n(--write not passed; numbers file not written - re-run with --write to commit)");
  }
}

main().catch((e) => {
  console.error("benchmark failed:", e);
  process.exit(1);
});
